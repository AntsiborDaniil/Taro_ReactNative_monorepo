export function faqMenuKeyboard(): InlineKeyboard {
  const keyboard = new InlineKeyboard();
  FAQ_ENTRIES.forEach((entry, index) => {
    keyboard.text(entry.button, `faq:${entry.id}`);
    if (index < FAQ_ENTRIES.length - 1) {
      keyboard.row();
    }
  });
  return keyboard;
}

export function faqBackKeyboard(): InlineKeyboard {
  return new InlineKeyboard().text('← Все вопросы', 'faq:menu');
}

export function findFaqEntry(id: string): FaqEntry | undefined {
  return FAQ_ENTRIES.find((entry) => entry.id === id);
}
